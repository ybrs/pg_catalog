//! Regenerate the committed catalog-view creation order.
//!
//! Run after adding, removing or editing a declared view (see
//! `VIEWS_TO_REGISTER` in `src/session.rs`):
//!
//! ```bash
//! cargo run --bin gen_view_order
//! ```
//!
//! A view body may reference another declared view, so views have to be created
//! in dependency order. Rather than derive that order by analysing the bodies --
//! which would mean parsing 139 SQL statements and getting every join, subquery
//! and CTE right -- this brute-forces it once: it builds a session context,
//! retries views until they all plan, and records the order that worked. An
//! order that provably created every view cannot be wrong about dependencies.
//!
//! Startup then follows the recorded order in a single pass. The retry there is
//! only a backstop, and warns if it ever fires, which is the signal that this
//! file is stale.

use std::fs;

const OUTPUT: &str = "pg_catalog_data/view_creation_order.txt";

#[tokio::main]
async fn main() {
    let order = datafusion_pg_catalog::session::discover_view_creation_order()
        .await
        .unwrap_or_else(|e| panic!("failed to discover the view creation order: {e}"));

    let mut contents = String::from(
        "# Catalog view creation order, one schema.view per line.\n\
         # Generated by `cargo run --bin gen_view_order` -- do not edit by hand.\n\
         # Views must be created in this order; each depends only on views above it.\n",
    );
    for key in &order {
        contents.push_str(key);
        contents.push('\n');
    }

    fs::write(OUTPUT, &contents).unwrap_or_else(|e| panic!("failed to write {OUTPUT}: {e}"));
    println!("wrote {OUTPUT} ({} views)", order.len());
}
